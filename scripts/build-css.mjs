#!/usr/bin/env node
/**
 * build-css — Tailwind CSS base + the publication's custom SCSS → assets/css/main.css
 *
 * Two passes, in this order:
 *
 *   1. `pnpm sass`  compiles scss/styles.scss → .build/custom.css
 *      (SCSS stays the authoring surface: nesting, partials, @use.)
 *   2. this script  wraps that output in Tailwind's layer stack and compiles it
 *      with the Tailwind engine, which expands `@apply` and emits any utility
 *      classes actually used in templates/.
 *
 * The layer order is declared up front (theme → base → components → utilities)
 * so utilities can override the custom component rules from a template class,
 * which is the normal Tailwind arrangement.
 *
 * NO PREFLIGHT ON PURPOSE. `tailwindcss/preflight.css` is not imported: the
 * page reset lives in scss/base/_page.scss and per-element type in
 * scss/partials/*. Preflight's bare-element resets (heading font-size/weight,
 * list markers, margins) would silently override rules this design sets
 * element by element. Add it back deliberately if that ever becomes wanted.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { compile } from 'tailwindcss';

const ROOT = path.resolve(import.meta.dirname, '..');
const CUSTOM_CSS = path.join(ROOT, '.build/custom.css');
const OUT = path.join(ROOT, 'assets/css/main.css');
const TEMPLATE_DIR = path.join(ROOT, 'templates');

if (!existsSync(CUSTOM_CSS)) {
    console.error('build-css: .build/custom.css is missing — run `pnpm sass` first.');
    process.exit(1);
}

const require = createRequire(path.join(ROOT, 'package.json'));

// Tailwind's default theme (tokens + utility definitions), without preflight.
const themeCss = readFileSync(require.resolve('tailwindcss/theme.css'), 'utf8');
const customCss = readFileSync(CUSTOM_CSS, 'utf8');

const input = [
    '@layer theme, base, components, utilities;',
    `@layer theme {\n${themeCss}\n}`,
    `@layer components {\n${customCss}\n}`,
    '@layer utilities {\n@tailwind utilities;\n}',
].join('\n\n');

// Class names from the templates, so `class="mt-4"` in markup works without a
// separate config step. Only class attributes are scanned — running the engine
// over raw file text picks up prose ("the fixed bar") as utility names.
const CLASS_ATTR = /\bclass\s*=\s*("[^"]*"|'[^']*')/g;

function* walk(dir) {
    for (const entry of readdirSync(dir)) {
        const full = path.join(dir, entry);
        if (statSync(full).isDirectory()) yield* walk(full);
        else yield full;
    }
}

const candidates = new Set();
for (const file of walk(TEMPLATE_DIR)) {
    const source = readFileSync(file, 'utf8');
    for (const [, value] of source.matchAll(CLASS_ATTR)) {
        for (const name of value.slice(1, -1).split(/\s+/)) {
            // drop `{{...}}` expressions, which are not class names
            if (name && !name.includes('{')) candidates.add(name);
        }
    }
}

const compiler = await compile(input, { base: ROOT });
const css = compiler.build([...candidates]);

writeFileSync(
    OUT,
    `/* Generated by scripts/build-css.mjs — edit scss/, not this file. */\n${css}\n`,
);

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`build-css: assets/css/main.css  ${kb(css.length)}  (${candidates.size} candidates)`);
